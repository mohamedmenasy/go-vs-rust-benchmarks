"""Generate spec/golden.json: expected values checked by the Go, Rust and
Python test suites. Anything a benchmark relies on for cross-language
equivalence (PRNG streams, digests, histogram buckets, known workload answers)
gets a golden entry here, computed by the independent Python reference.

Usage: scripts/bench golden [--check]
"""

from __future__ import annotations

import json
import struct
from pathlib import Path

from . import refimpl as R

U64_SAMPLES = [
    0, 1, 2, 63, 64, 65, 100, 127, 128, 129, 1000, 4095, 4096, 65535,
    1_000_000, 123_456_789, 1 << 32, (1 << 40) + 12345, 1 << 62,
    (1 << 63) + 1, R.MASK64,
]


def _splitmix_section() -> dict:
    streams = []
    for seed in (0, 1, 42, 0xDEADBEEF, R.MASK64):
        g = R.SplitMix64(seed)
        streams.append({"seed": R.hexu64(seed), "next": [R.hexu64(g.next()) for _ in range(8)]})
    below = []
    for seed, n in ((7, 1000), (7, 1 << 31), (99, 3), (12345, 1_000_003)):
        g = R.SplitMix64(seed)
        below.append({"seed": R.hexu64(seed), "n": n, "values": [g.below(n) for _ in range(8)]})
    floats = []
    for seed in (7, 2024):
        g = R.SplitMix64(seed)
        values = [g.float64() for _ in range(6)]
        # Compared via IEEE-754 bit patterns: JSON float parsing is not
        # correctly rounded in every library (serde_json's default is
        # best-effort), so tests must not depend on it.
        floats.append({
            "seed": R.hexu64(seed),
            "values": values,
            "bits": [R.hexu64(struct.unpack("<Q", struct.pack("<d", v))[0]) for v in values],
        })
    return {"streams": streams, "below": below, "float64": floats}


def _digest_section() -> dict:
    fnv_inputs = ["", "a", "foobar", "hello, world", "Go vs Rust ✓ 🚀"]
    fnv = [{"input": s, "hash": R.hexu64(R.fnv1a64(s.encode()))} for s in fnv_inputs]
    mix = [{"in": R.hexu64(x), "out": R.hexu64(R.mix64(x))} for x in U64_SAMPLES]
    seqs = [[], [1], [1, 2, 3], [3, 2, 1], U64_SAMPLES]
    ordered = []
    unordered = []
    for s in seqs:
        d, u = R.Digest(), R.Unordered()
        for x in s:
            d.add(x)
            u.add(x)
        words = [R.hexu64(x) for x in s]
        ordered.append({"words": words, "sum": R.hexu64(d.sum())})
        unordered.append({"words": words, "sum": R.hexu64(u.sum())})
    return {"fnv1a64": fnv, "mix64": mix, "ordered": ordered, "unordered": unordered}


def _hist_section() -> list:
    return [{"value": R.hexu64(v), "bucket": R.hist_bucket(v)} for v in U64_SAMPLES]


def build() -> dict:
    from . import golden_workloads  # noqa: PLC0415 - optional per-category additions

    doc = {
        "_comment": "Generated by scripts/benchctl/golden.py - do not edit by hand. u64 values are 16-digit lowercase hex.",
        "splitmix64": _splitmix_section(),
        "digest": _digest_section(),
        "histogram": _hist_section(),
    }
    doc.update(golden_workloads.sections())
    return doc


def golden_path(root: Path) -> Path:
    return root / "spec" / "golden.json"


def write(root: Path) -> Path:
    path = golden_path(root)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(build(), indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    return path


def check(root: Path) -> bool:
    path = golden_path(root)
    if not path.exists():
        return False
    return json.loads(path.read_text(encoding="utf-8")) == json.loads(json.dumps(build(), ensure_ascii=False))
