"""Generate docs/BENCHMARKS.md from bench.toml: for every benchmark the Go and
Rust implementations, the exact command, input, sizes per profile, warmup,
measurement and repetition settings."""

from __future__ import annotations

from collections import defaultdict
from pathlib import Path

from . import orchestrate
from .spec import Spec
from .util import ROOT

CATEGORY_TITLES = {
    "selftest": "Harness self-test",
    "cpu": "1. CPU-bound workloads",
    "memory": "2. Memory",
    "json": "3. JSON",
    "http": "4. HTTP server",
    "concurrency": "5. Concurrency",
    "io": "6. File I/O",
    "strings": "7. String processing",
    "collections": "8. Collections",
    "startup": "9. Startup time",
    "binsize": "10. Binary size",
    "compile": "11. Compilation",
}


def _source(lang: str, w) -> str:
    if lang == "go":
        return f"`go/{w.bin}/`"
    return f"`rust/{w.bin}/`"


def _timing_str(t: dict) -> str:
    return (
        f"warmup ≥{t.get('warmup_iters', '?')} iters & ≥{t.get('warmup_min_ms', '?')} ms; "
        f"measure ≥{t.get('iters', '?')} iters & ≥{t.get('min_ms', '?')} ms"
    )


def render(spec: Spec) -> str:
    lines = [
        "# Benchmark catalog",
        "",
        "<!-- Generated by `scripts/bench docs` from bench.toml. Do not edit by hand. -->",
        "",
        "Every row is one Go-vs-Rust comparison. *Rounds* are independent process",
        "launches (Go and Rust interleaved in a seeded random order within each round);",
        "*timing* is the per-process protocol described in METHODOLOGY.md.",
        "Commands show the `standard` profile; `quick`/`full` change sizes, rounds and timing.",
        "",
        "| Profile | Rounds | Per-process timing |",
        "|---|---|---|",
    ]
    for name, p in spec.profiles.items():
        lines.append(f"| `{name}` | {p.rounds} | {_timing_str(p.timing)} |")
    lines.append("")
    by_cat: dict[str, list] = defaultdict(list)
    for w in spec.workloads:
        by_cat[w.category].append(w)
    for cat, ws in by_cat.items():
        lines += [f"## {CATEGORY_TITLES.get(cat, cat)}", ""]
        for w in ws:
            lines += [f"### `{w.id}`", "", w.desc.strip(), ""]
            if w.notes:
                lines += [f"*Notes:* {w.notes.strip()}", ""]
            impl = ", ".join(f"{lang}: `{w.impl_for(lang)}` in {_source(lang, w)}" for lang in w.langs)
            lines.append(f"- **Implementations:** {impl}")
            lines.append(f"- **Track:** `{w.track}`" + (f" (variant of `{w.variant_of}`)" if w.variant_of else ""))
            if w.flavor:
                lines.append(f"- **Build flavor:** {', '.join(f'{k}: `{v}`' for k, v in w.flavor.items())}")
            if w.env:
                lines.append(f"- **Environment:** {', '.join(f'{k}: `{v}`' for k, v in w.env.items())}")
            lines.append(f"- **CPU pinning:** `{w.cores}` → cores `{spec.cpus(w.cores)}`")
            sizes = []
            for s in w.sizes:
                inputs = f" input `{', '.join(s.inputs())}`" if s.inputs() else ""
                sizes.append(f"`{s.label}` ({'/'.join(s.profiles)}){inputs}")
            lines.append(f"- **Sizes:** {'; '.join(sizes)}")
            if w.kind == "harness":
                for prof in spec.profiles:
                    lines.append(
                        f"- **{prof}:** {spec.rounds_for(prof, w)} rounds; {_timing_str(spec.timing_for(prof, w))}"
                    )
                std = next((s for s in w.sizes if "standard" in s.profiles), w.sizes[0])
                t = spec.timing_for("standard", w)
                for lang in w.langs:
                    args = orchestrate.harness_args(w, std, lang, t)
                    args = [a.replace(str(ROOT) + "/", "") for a in args]
                    flavor = w.flavor_for(lang)
                    bindir = f"bin/{lang}-{flavor}" if flavor else f"bin/{lang}"
                    lines.append(f"- **Command ({lang}):** `taskset -c {spec.cpus(w.cores)} {bindir}/{w.bin} {' '.join(args)}`")
            else:
                lines.append(f"- **Driver:** `scripts/benchctl` category `{w.kind}` (see METHODOLOGY.md)")
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def write(spec: Spec) -> Path:
    path = ROOT / "docs" / "BENCHMARKS.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(spec), encoding="utf-8")
    return path
